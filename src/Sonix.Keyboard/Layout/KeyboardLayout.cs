using System.Collections.Concurrent;
using System.Text.Json;

namespace Sonix.Keyboard.Layout;

/// <summary>One physical key from the stock layouts/rgb-keyboard.xml: <see cref="Led"/> is both the LED index and the key index (they are equal in the vendor files).</summary>
public sealed record LayoutKey(string Name, int Led, int Code, int X, int Y, int W, int H)
{
    /// <summary>Slot in the remap tables (key_index in the vendor XML).</summary>
    public int Index => Led;
}

public sealed record KeyboardLayout(int Width, int Height, List<LayoutKey> Keys)
{
    private static readonly ConcurrentDictionary<string, KeyboardLayout> Cache = new();

    /// <summary>The model's embedded layout (generated by re/layout2json.py from the stock XML).</summary>
    public static KeyboardLayout Load(KeyboardModel model) => Cache.GetOrAdd(model.LayoutResource, resource =>
    {
        var asm = typeof(KeyboardLayout).Assembly;
        var name = asm.GetManifestResourceNames().First(n => n.EndsWith(resource, StringComparison.OrdinalIgnoreCase));
        using var s = asm.GetManifestResourceStream(name) ?? throw new FileNotFoundException($"Embedded layout {resource} missing");
        return JsonSerializer.Deserialize<KeyboardLayout>(s, new JsonSerializerOptions { PropertyNameCaseInsensitive = true })!;
    });

    public LayoutKey? ByIndex(int index) => Keys.FirstOrDefault(k => k.Index == index);

    public LayoutKey? ByName(string name) => Keys.FirstOrDefault(k => k.Name.Equals(name, StringComparison.OrdinalIgnoreCase));
}
